const LangContext = React.createContext({ lang: "es", t: (k) => k });

function LangProvider({ children }) {
  const [lang, setLang] = React.useState(() => localStorage.getItem("authentiq_lang") || "es");
  React.useEffect(() => { localStorage.setItem("authentiq_lang", lang); }, [lang]);
  const t = React.useCallback((key) => DICT[lang][key] || key, [lang]);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}
function useT() { return React.useContext(LangContext); }

window.LangProvider = LangProvider;
window.useT = useT;
